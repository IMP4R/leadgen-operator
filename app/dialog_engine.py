def _post(messages, temperature=0.7, max_retries=4):
    payload = {
        "model": config.GEMINI_MODEL,
        "messages": messages,
        "temperature": temperature,
    }
    req = urllib.request.Request(
        ENDPOINT,
        data=json.dumps(payload).encode("utf-8"),
        headers={
            "Authorization": "Bearer " + config.GEMINI_API_KEY,
            "Content-Type": "application/json",
        },
        method="POST",
    )
    last_err = None
    for attempt in range(max_retries):
        try:
            with urllib.request.urlopen(req, timeout=60) as resp:
                body = json.loads(resp.read().decode("utf-8"))
            if not isinstance(body, dict):
                raise ValueError("model response is not an object")
            choices = body.get("choices") or []
            if not choices:
                raise ValueError("model response has no choices")
            choice = choices[0] or {}
            message = choice.get("message") or {}
            content = message.get("content")
            if not content:
                reason = choice.get("finish_reason") or body.get("promptFeedback") or "unknown"
                raise ValueError("model response has no message content; reason=%s" % reason)
            return content
        except urllib.error.HTTPError as e:
            last_err = e
            if e.code == 429 and attempt < max_retries - 1:
                time.sleep(15 * (attempt + 1))
                continue
            raise
        except (urllib.error.URLError, TimeoutError, ValueError,
                KeyError, IndexError, TypeError, AttributeError) as e:
            last_err = e
            if attempt < max_retries - 1:
                time.sleep(5 * (attempt + 1))
                continue
            raise
    raise last_err


def _extract_json(text):
    text = text.strip()
    if text.startswith("```"):
        lines = text.split("\n")
        lines = [l for l in lines if not l.strip().startswith("```")]
        text = "\n".join(lines)
    start = text.find("{")
    end = text.rfind("}")
    if start == -1 or end == -1:
        raise ValueError("no JSON in model output: " + text[:200])
    return json.loads(text[start:end + 1])


