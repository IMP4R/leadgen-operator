            "как основу по смыслу и тону: коротко и прямо уточнить, актуален ли найм или "
            "подбор сотрудников. Не копируй запрещённые части примеров.\n\n"
            "КРИТИЧЕСКИЕ ЗАПРЕТЫ ДЛЯ КАЖДОГО ВАРИАНТА:\n"
