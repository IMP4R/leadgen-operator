LEAD_OPEN = "««СООБЩЕНИЕ ЛИДА»»\n"
LEAD_CLOSE = "\n««КОНЕЦ СООБЩЕНИЯ ЛИДА»»"


class DialogEngine:
    def __init__(self):
        if not config.GEMINI_API_KEY:
            raise RuntimeError("GEMINI_API_KEY is empty in .env")

    @staticmethod
    def _wrap_lead(text):
        return LEAD_OPEN + text + LEAD_CLOSE

    def suggest(self, history, incoming, incoming_is_lead=True, temperature=0.7,
                allow_intro=None):
        if allow_intro is None:
            allow_intro = policy.asks_identity(incoming) if incoming_is_lead else False
        messages = [{"role": "system", "content": SYSTEM_PROMPT}]
        for m in (history or []):
            role = m.get("role") or "user"
            text = m.get("text", "")
            if role == "user":
                text = self._wrap_lead(text)
            messages.append({"role": role, "content": text})
        content = self._wrap_lead(incoming) if incoming_is_lead else incoming
        messages.append({"role": "user", "content": content})
        data = _extract_json(_post(messages, temperature=temperature))
        cleaned = policy.sanitize_variants(data.get("variants"), allow_intro=allow_intro)
        if not cleaned:
            print("[engine] варианты с плейсхолдерами или визиткой — перегенерирую")
            messages.append({"role": "user", "content": REPAIR_HINT})
            retry = _extract_json(_post(messages, temperature=temperature))
            cleaned = policy.sanitize_variants(retry.get("variants"),
                                               allow_intro=allow_intro)
            if cleaned:
                retry["variants"] = cleaned
                return retry
            cleaned = [policy.neutral_fallback()]
        data["variants"] = cleaned
        return data

